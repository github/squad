import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  CLIENT_IDS,
  buildCoordinatorInstructions,
  installClients,
  uninstallClients,
} from '../packages/squad-sdk/src/client/adapters/index.js';
import { claudeCoordinatorSkills } from '../packages/squad-sdk/src/client/adapters/coordinator.js';

const MCP = { command: 'squad', args: ['state-mcp'] };
const SKILLS = ['squad-coordinator-init-mode', 'squad-coordinator-ralph-mode', 'squad-coordinator-ceremonies', 'squad-coordinator-issues-mode', 'squad-coordinator-prd-mode'];

describe('Claude coordinator slimming', () => {
  const claude = buildCoordinatorInstructions('claude');

  it('replaces each on-demand item with a stub that names its skill', () => {
    expect(claudeCoordinatorSkills().map((k) => k.name)).toEqual(SKILLS);
    for (const k of SKILLS) expect(claude).toContain(`\`${k}\``);
    // The loop body itself lives only in the skill.
    expect(claude).not.toContain('**Scan** with the `gh` CLI');
    expect(Buffer.byteLength(claude)).toBeLessThan(Buffer.byteLength(buildCoordinatorInstructions('kiro')));
  });

  it('keeps the rules that must hold before a skill is loaded', () => {
    expect(claude).toMatch(/NEVER with glob\/grep\/search tools/);
    expect(claude).toMatch(/NEVER overwrite or re-cast it/);
    expect(claude).toMatch(/never delegate the loop itself/);
  });

  it('moves every item verbatim: the skill bodies match the full digest other hosts load', () => {
    const kiro = buildCoordinatorInstructions('kiro');
    for (const k of claudeCoordinatorSkills()) {
      const item = k.body.split('\n\n').slice(2).join('\n\n').trimEnd();
      expect(kiro, k.name).toContain(item);
      expect(claude, k.name).not.toContain(item);
    }
  });

  it('leaves every other host digest untouched', () => {
    for (const id of CLIENT_IDS.filter((h) => h !== 'claude')) {
      const t = buildCoordinatorInstructions(id);
      expect(t, id).toContain('**Scan** with the `gh` CLI');
      expect(t, id).not.toContain('squad-coordinator-');
    }
  });
});

describe('Claude skills projection', () => {
  let root: string;
  const skillFile = (name: string) => path.join(root, '.claude/skills', name, 'SKILL.md');
  const template = (name: string, body = `---\nname: "${name}"\ndescription: "Template ${name}"\n---\n\n## Context\n\nUse ${name}.\n`) => {
    fs.mkdirSync(path.join(root, '.squad/templates/skills', name), { recursive: true });
    fs.writeFileSync(path.join(root, '.squad/templates/skills', name, 'SKILL.md'), body);
  };

  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'squad-claude-skills-'));
    template('git-workflow');
    template('distributed-mesh');
    fs.writeFileSync(path.join(root, '.squad/templates/skills/distributed-mesh/sync-mesh.sh'), 'echo hi\n');
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it('projects template skills with the generated note after the frontmatter, plus the coordinator skills', () => {
    installClients(['claude'], { root, mcp: MCP });
    expect(fs.readdirSync(path.join(root, '.claude/skills')).sort()).toEqual(['distributed-mesh', 'git-workflow', ...SKILLS].sort());
    const git = fs.readFileSync(skillFile('git-workflow'), 'utf8');
    expect(git).toMatch(/^---\nname: "git-workflow"\ndescription: "Template git-workflow"\n---\n<!-- Generated by Squad\./);
    expect(git).toContain('Use git-workflow.');
    expect(fs.readFileSync(skillFile('distributed-mesh'), 'utf8')).toContain('`.squad/templates/skills/distributed-mesh/`');
    const ralph = fs.readFileSync(skillFile('squad-coordinator-ralph-mode'), 'utf8');
    expect(ralph).toMatch(/^---\nname: squad-coordinator-ralph-mode\ndescription: "Squad coordinator only: Ralph mode/);
    expect(ralph).toContain('**Scan** with the `gh` CLI');
    expect(installClients(['claude'], { root, mcp: MCP }).every((r) => r.action === 'unchanged')).toBe(true);
  });

  it('a team skill of the same name wins: its template is not projected (and is removed if it was)', () => {
    installClients(['claude'], { root, mcp: MCP });
    fs.mkdirSync(path.join(root, '.squad/skills/git-workflow'), { recursive: true });
    fs.writeFileSync(path.join(root, '.squad/skills/git-workflow/SKILL.md'), '---\nname: git-workflow\n---\nTeam rules.\n');
    const results = installClients(['claude'], { root, mcp: MCP });
    expect(results.find((r) => r.path === '.claude/skills/git-workflow/SKILL.md')?.action).toBe('removed');
    expect(fs.existsSync(path.join(root, '.claude/skills/git-workflow'))).toBe(false);
  });

  it('never overwrites or removes a user-authored skill', () => {
    const mine = '---\nname: git-workflow\ndescription: mine\n---\nMine.\n';
    fs.mkdirSync(path.dirname(skillFile('git-workflow')), { recursive: true });
    fs.writeFileSync(skillFile('git-workflow'), mine);
    fs.mkdirSync(path.dirname(skillFile('my-own')), { recursive: true });
    fs.writeFileSync(skillFile('my-own'), 'mine too\n');
    expect(installClients(['claude'], { root, mcp: MCP }).find((r) => r.path === '.claude/skills/git-workflow/SKILL.md')?.action).toBe('skipped');
    uninstallClients(['claude'], { root, mcp: MCP });
    expect(fs.readFileSync(skillFile('git-workflow'), 'utf8')).toBe(mine);
    expect(fs.readFileSync(skillFile('my-own'), 'utf8')).toBe('mine too\n');
    expect(fs.existsSync(path.join(root, '.claude/skills/squad-coordinator-ralph-mode'))).toBe(false);
  });

  it('rollback removes every generated skill, even after its template is gone, and prunes .claude', () => {
    installClients(['claude'], { root, mcp: MCP });
    fs.rmSync(path.join(root, '.squad/templates'), { recursive: true });
    uninstallClients(['claude'], { root, mcp: MCP });
    expect(fs.existsSync(path.join(root, '.claude'))).toBe(false);
  });
});
