/**
 * Claude Code member subagents (#2442 Phase 2): charters compile to `.claude/agents/<id>.md`.
 */
import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  installClients,
  uninstallClients,
} from '../packages/squad-sdk/src/client/adapters/index.js';
import {
  parseClaudeHostSettings,
  renderClaudeMember,
} from '../packages/squad-sdk/src/client/adapters/claude-members.js';

const NOTE = '<!-- Generated by Squad. -->';
const MCP = { command: 'squad', args: ['state-mcp'] };

function charter(opts: { model?: string; effort?: string; tier?: string; extension?: string; purpose?: string } = {}): string {
  return [
    '# Dallas — Backend Dev',
    '',
    '## Identity',
    '- **ID:** `dallas`',
    ...(opts.purpose ? [`- **Purpose:** ${opts.purpose}`] : []),
    '',
    '## Accountable Responsibilities',
    '- APIs',
    '',
    '## Non-Responsibilities',
    '- UI',
    '',
    '## Collaboration and Review Authority',
    '- Reviews API changes',
    '',
    '## Model',
    `- **Preferred:** ${opts.model ?? 'auto'}`,
    `- **Reasoning Effort:** ${opts.effort ?? 'auto'}`,
    `- **Context Tier:** ${opts.tier ?? 'auto'}`,
    ...(opts.extension ? ['', opts.extension] : []),
    '',
  ].join('\n');
}

function frontmatter(md: string): Record<string, string> {
  const block = md.match(/^---\n([\s\S]*?)\n---\n/)![1]!;
  return Object.fromEntries(block.split('\n').map((l) => [l.slice(0, l.indexOf(':')), l.slice(l.indexOf(':') + 1).trim()]));
}

describe('renderClaudeMember: charter → Claude subagent frontmatter', () => {
  it('maps a Claude model and reasoning effort, and names the member by id', () => {
    const fm = frontmatter(renderClaudeMember('dallas', charter({ model: '`sonnet`', effort: 'high' }), [], '.squad', NOTE));
    expect(fm).toMatchObject({ name: 'dallas', model: 'sonnet', effort: 'high' });
  });

  it('omits model and effort for auto (charter §6: auto is never a literal override)', () => {
    const md = renderClaudeMember('dallas', charter(), [], '.squad', NOTE);
    const fm = frontmatter(md);
    expect(fm.model).toBeUndefined();
    expect(fm.effort).toBeUndefined();
    expect(md).not.toContain('not projected');
  });

  it('reports a non-Claude model and an unapplied long_context tier instead of dropping them silently', () => {
    const md = renderClaudeMember('dallas', charter({ model: 'gpt-5', tier: 'long_context' }), [], '.squad', NOTE);
    expect(frontmatter(md).model).toBeUndefined();
    expect(md).toMatch(/not projected to Claude Code: Model `gpt-5` .*Context Tier `long_context`/);
  });

  it('keeps an explicit long-context Claude model and does not report the tier', () => {
    const md = renderClaudeMember('dallas', charter({ model: 'sonnet[1m]', tier: 'long_context' }), [], '.squad', NOTE);
    expect(frontmatter(md).model).toBe('sonnet[1m]');
    expect(md).not.toContain('long_context');
  });

  it('builds a single-line description from Purpose and routing ownership', () => {
    const md = renderClaudeMember(
      'dallas',
      charter({ purpose: 'Owns the "API" layer.' }),
      [{ workType: 'Backend', routeTo: 'dallas' }, { workType: 'UI', routeTo: 'lambert' }],
      '.squad',
      NOTE,
    );
    const description = JSON.parse(frontmatter(md).description!);
    expect(description).toBe('Owns the "API" layer. Owns: Backend. Spawned by the Squad coordinator.');
  });

  it('points the subagent at its charter and history, and forbids nested dispatch', () => {
    const md = renderClaudeMember('dallas', charter(), [], 'team/.squad', NOTE);
    expect(md).toContain('`team/.squad/agents/dallas/charter.md`');
    expect(md).toContain('`team/.squad/agents/dallas/history.md`');
    expect(md).toContain('do not spawn subagents of your own');
    expect(md).toContain(NOTE);
  });
});

describe('X-squad-host-claude charter extension', () => {
  it('projects Tools and Isolation (case-insensitive heading, backticks allowed)', () => {
    const ext = '## x-squad-host-claude\n- **Tools:** `Read`, Grep, Glob, mcp__squad_state__squad_state_read\n- **Isolation:** worktree';
    const fm = frontmatter(renderClaudeMember('dallas', charter({ extension: ext }), [], '.squad', NOTE));
    expect(fm.tools).toBe('Read, Grep, Glob, mcp__squad_state__squad_state_read');
    expect(fm.isolation).toBe('worktree');
  });

  it('rejects values that could escape the frontmatter and reports them', () => {
    const settings = parseClaudeHostSettings(
      charter({ extension: '## X-squad-host-claude\n- **Tools:** Read, Bash\nmodel: opus\n- **Isolation:** container' }),
    );
    // The stray `model: opus` line is not a field; it cannot reach the frontmatter.
    expect(settings.tools).toEqual(['Read', 'Bash']);
    expect(settings.isolation).toBeUndefined();
    expect(settings.rejected).toEqual(['Isolation `container` (only `worktree` is supported)']);
    expect(parseClaudeHostSettings(charter({ extension: '## X-squad-host-claude\n- **Tools:** Read, "x": y' })).rejected[0]).toMatch(/^Tools/);
  });

  it('ignores the extension of another host and fields after the next section', () => {
    const ext = '## X-squad-host-kiro\n- **Tools:** Read\n\n## X-squad-host-claude\n- **Isolation:** worktree\n\n## X-other-thing\n- **Tools:** Bash';
    const settings = parseClaudeHostSettings(charter({ extension: ext }));
    expect(settings).toEqual({ isolation: 'worktree', rejected: [] });
  });
});

describe('Claude member projection: apply, skip user files, prune, rollback', () => {
  let root: string;
  const writeCharter = (id: string, body = charter()) => {
    fs.mkdirSync(path.join(root, '.squad/agents', id), { recursive: true });
    fs.writeFileSync(path.join(root, '.squad/agents', id, 'charter.md'), body);
  };
  const agentFile = (id: string) => path.join(root, '.claude/agents', `${id}.md`);

  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'squad-claude-members-'));
    writeCharter('dallas', charter({ model: 'opus', effort: 'max' }));
    writeCharter('scribe');
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it('writes one subagent per member charter next to the coordinator', () => {
    const results = installClients(['claude'], { root, mcp: MCP });
    expect(results.find((r) => r.path === '.claude/agents/dallas.md')?.action).toBe('created');
    expect(fs.readdirSync(path.join(root, '.claude/agents')).sort()).toEqual(['dallas.md', 'scribe.md', 'squad.md']);
    expect(frontmatter(fs.readFileSync(agentFile('dallas'), 'utf8'))).toMatchObject({ model: 'opus', effort: 'max' });
    expect(installClients(['claude'], { root, mcp: MCP }).every((r) => r.action === 'unchanged')).toBe(true);
  });

  it('never projects a member named like the coordinator', () => {
    writeCharter('squad');
    installClients(['claude'], { root, mcp: MCP });
    expect(fs.readFileSync(agentFile('squad'), 'utf8')).toContain('name: squad\ndescription: "Squad coordinator');
  });

  it('skips and reports a user-authored file at a member path, on install and on rollback', () => {
    fs.mkdirSync(path.join(root, '.claude/agents'), { recursive: true });
    const mine = '---\nname: dallas\ndescription: my own\n---\nHand-written.\n';
    fs.writeFileSync(agentFile('dallas'), mine);
    const results = installClients(['claude'], { root, mcp: MCP });
    expect(results.find((r) => r.path === '.claude/agents/dallas.md')).toMatchObject({ action: 'skipped' });
    expect(fs.readFileSync(agentFile('dallas'), 'utf8')).toBe(mine);

    const removed = uninstallClients(['claude'], { root, mcp: MCP });
    expect(removed.find((r) => r.path === '.claude/agents/dallas.md')).toMatchObject({ action: 'skipped' });
    expect(fs.readFileSync(agentFile('dallas'), 'utf8')).toBe(mine);
    expect(fs.existsSync(agentFile('scribe'))).toBe(false);
  });

  it('removes the generated file of a member whose charter is gone, but not user files', () => {
    installClients(['claude'], { root, mcp: MCP });
    fs.writeFileSync(agentFile('helper'), '---\nname: helper\ndescription: mine\n---\n');
    fs.rmSync(path.join(root, '.squad/agents/dallas'), { recursive: true });
    const results = installClients(['claude'], { root, mcp: MCP });
    expect(results.find((r) => r.path === '.claude/agents/dallas.md')?.action).toBe('removed');
    expect(fs.existsSync(agentFile('dallas'))).toBe(false);
    expect(fs.existsSync(agentFile('helper'))).toBe(true);
  });

  it('rollback removes generated members even after their charters were deleted, and prunes .claude', () => {
    installClients(['claude'], { root, mcp: MCP });
    fs.rmSync(path.join(root, '.squad/agents'), { recursive: true });
    uninstallClients(['claude'], { root, mcp: MCP });
    expect(fs.existsSync(path.join(root, '.claude'))).toBe(false);
  });

  it('honors a custom squadDir', () => {
    fs.mkdirSync(path.join(root, 'team'), { recursive: true });
    fs.renameSync(path.join(root, '.squad'), path.join(root, 'team/.squad'));
    installClients(['claude'], { root, mcp: MCP, squadDir: 'team/.squad' });
    expect(fs.readFileSync(agentFile('dallas'), 'utf8')).toContain('`team/.squad/agents/dallas/charter.md`');
  });
});

describe('CLI: squad upgrade --client claude and squad cast write member subagents', () => {
  let root: string;
  const prev = process.env['SQUAD_NONINTERACTIVE'];
  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'squad-claude-cli-'));
    process.env['SQUAD_NONINTERACTIVE'] = '1';
    vi.spyOn(console, 'log').mockImplementation(() => undefined);
    vi.spyOn(console, 'warn').mockImplementation(() => undefined);
  });
  afterEach(() => {
    vi.restoreAllMocks();
    if (prev === undefined) delete process.env['SQUAD_NONINTERACTIVE'];
    else process.env['SQUAD_NONINTERACTIVE'] = prev;
    fs.rmSync(root, { recursive: true, force: true });
  });

  it('projects the built-ins, then a newly cast member', async () => {
    const { runInit } = await import('../packages/squad-cli/src/cli/core/init.js');
    const { runUpgrade } = await import('../packages/squad-cli/src/cli/core/upgrade.js');
    const { runCastAdd } = await import('../packages/squad-cli/src/cli/commands/cast.js');
    await runInit(root, { includeWorkflows: false, includeVscodeDefault: false });
    expect(fs.existsSync(path.join(root, '.claude'))).toBe(false);

    await runUpgrade(root, { clients: ['copilot', 'claude'] });
    const agents = () => fs.readdirSync(path.join(root, '.claude/agents')).sort();
    expect(agents()).toEqual(expect.arrayContaining(['fact-checker.md', 'rai.md', 'ralph.md', 'scribe.md', 'squad.md']));
    expect(agents()).not.toContain('dallas.md');

    await runCastAdd(root, { name: 'Dallas', role: 'Backend Dev' });
    expect(agents()).toContain('dallas.md');
    expect(fs.readFileSync(path.join(root, '.claude/agents/dallas.md'), 'utf8')).toMatch(/^---\nname: dallas\n/);
  }, 60_000);

  it('squad cast writes nothing under .claude when claude is not configured', async () => {
    const { runInit } = await import('../packages/squad-cli/src/cli/core/init.js');
    const { runCastAdd } = await import('../packages/squad-cli/src/cli/commands/cast.js');
    await runInit(root, { includeWorkflows: false, includeVscodeDefault: false });
    await runCastAdd(root, { name: 'Dallas', role: 'Backend Dev' });
    expect(fs.existsSync(path.join(root, '.claude'))).toBe(false);
  }, 60_000);
});
