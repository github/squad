/** Insert the generated note after a SKILL.md frontmatter, which must stay first. */
function withNote(markdown: string): string {
  const text = markdown.replace(/\r\n?/g, '\n');
  const fm = text.match(/^---\n[\s\S]*?\n---\n/);
  return fm ? `${fm[0]}${NOTE}\n${text.slice(fm[0].length)}` : `${NOTE}\n\n${text}`;
}

function walk(dir: string, rel = ''): string[] {
  const out: string[] = [];
  for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...walk(dir, r));
    else if (e.isFile()) out.push(r);
  }
  return out;
}

