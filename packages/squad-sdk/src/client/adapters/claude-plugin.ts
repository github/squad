/** Every file of the plugin, relative to its root. */
export function buildClaudePlugin(opts: BuildClaudePluginOptions): ClaudePluginFile[] {
  const files: ClaudePluginFile[] = [];
  files.push({
    path: '.claude-plugin/plugin.json',
    content: json({
      name: CLAUDE_PLUGIN_NAME,
      version: opts.version,
      description: DESCRIPTION,
      author: { name: 'Brady Gaster', url: 'https://github.com/bradygaster' },
      homepage: REPOSITORY,
      repository: REPOSITORY,
      license: 'MIT',
      keywords: ['squad', 'multi-agent', 'coordinator', 'subagents', 'mcp'],
    }),
  });
  files.push({
    path: 'agents/squad.md',
    content:
      `---\nname: squad\ndescription: ${JSON.stringify(
        'Squad coordinator: routes work to a team of specialist agents and keeps shared team state consistent via the squad_state MCP backend.',
      )}\n---\n${NOTE}\n\n${claudePluginCoordinatorInstructions()}`,
  });

  const skillNames = new Set<string>();
  for (const k of claudeCoordinatorSkills()) {
    skillNames.add(k.name);
    files.push({
      path: `skills/${k.name}/SKILL.md`,
      content: `---\nname: ${k.name}\ndescription: ${JSON.stringify(k.description)}\n---\n${NOTE}\n\n${k.body}`,
    });
  }
  const templates = fs
    .readdirSync(opts.templateSkillsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && NAME_RE.test(e.name) && !skillNames.has(e.name))
    .map((e) => e.name)
    .sort();
  for (const name of templates) {
    const dir = path.join(opts.templateSkillsDir, name);
    if (!fs.existsSync(path.join(dir, 'SKILL.md'))) continue;
    for (const rel of walk(dir)) {
      const raw = fs.readFileSync(path.join(dir, rel), 'utf8').replace(/\r\n?/g, '\n');
      files.push({
        path: `skills/${name}/${rel}`,
        content: rel === 'SKILL.md' ? withNote(raw) : raw,
        executable: rel.endsWith('.sh') ? true : undefined,
      });
    }
  }

  for (const c of COMMANDS) files.push({ path: `commands/${c.name}.md`, content: commandFile(c) });
  files.push({ path: 'hooks/hooks.json', content: hooksJson() });
  files.push({
    path: '.mcp.json',
    content: json({
      mcpServers: { squad_state: { command: 'node', args: ['${CLAUDE_PLUGIN_ROOT}/scripts/squad.mjs', 'state-mcp'] } },
    }),
  });
  files.push({ path: 'scripts/squad.mjs', content: CLAUDE_PLUGIN_LAUNCHER, executable: true });
  files.push({
    path: 'bin/squad',
    content: `#!/bin/sh\n# ${NOTE_TEXT}\nexec node "$(dirname "$0")/../scripts/squad.mjs" "$@"\n`,
    executable: true,
  });
  files.push({ path: 'bin/squad.cmd', content: `@echo off\nrem ${NOTE_TEXT}\nnode "%~dp0..\\scripts\\squad.mjs" %*\n` });
  files.push({ path: 'README.md', content: readme(opts.version) });
  files.push({ path: 'LICENSE', content: opts.license.replace(/\r\n?/g, '\n') });
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

