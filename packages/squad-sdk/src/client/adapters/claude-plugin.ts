  for (const event of CLAUDE_HOOK_EVENTS) {
    const handler = {
      type: 'command',
      command: `node "\${CLAUDE_PLUGIN_ROOT}/scripts/squad.mjs" hook claude ${event} --plugin`,
      timeout: HOOK_TIMEOUT_SECONDS,
    };
    const matcher = claudeHookMatcher(event as ClaudeHookEvent, { plugin: true });
    hooks[event] = [matcher ? { matcher, hooks: [handler] } : { hooks: [handler] }];
  }
